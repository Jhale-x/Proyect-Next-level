        <h2>1. ¿Qué son las Cookies?</h2>
        <p>Las cookies son pequeños archivos de texto que los sitios web almacenan en su navegador o dispositivo al visitarlos.
            Estos archivos permiten que el sitio "recuerde" sus acciones o preferencias (como inicio de sesión, idioma o
            visualización) para que no tenga que volver a configurarlos cada vez que regresa al sitio o navega por nuestras
            páginas.</p>

        <h2>2. Tipos de Cookies que Utilizamos</h2>
        <p>En Next Level School utilizamos las siguientes categorías de cookies para prestar un servicio de calidad:</p>
        <ul>
            <li><strong>Cookies Técnicas (Estrictamente Necesarias):</strong> Son esenciales para permitirle navegar por nuestro
                sitio y utilizar sus funciones, como acceder a áreas seguras o la Intranet. Sin estas cookies, los servicios de
                matrícula y acceso a la plataforma virtual no podrían funcionar correctamente.</li>
            <li><strong>Cookies de Funcionalidad:</strong> Permiten que nuestro sitio recuerde las opciones que usted elija para
                ofrecerle una experiencia más personalizada. Por ejemplo, permiten mostrar los mapas de nuestras sedes o reproducir
                los videos de nuestras clases y eventos escolares de forma integrada.</li>
            <li><strong>Cookies de Rendimiento y Análisis:</strong> Estas cookies recopilan información anónima sobre cómo los
                estudiantes y padres de familia interactúan con nuestro portal. Nos ayudan a entender qué contenidos son más
                visitados y a mejorar la navegación del sitio.</li>
        </ul>

