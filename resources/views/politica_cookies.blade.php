        <p>Al acceder y navegar por nuestro sitio web, usted consiente el uso de las cookies mencionadas anteriormente. La base
            legal para el uso de cookies técnicas es la prestación del servicio educativo solicitado, mientras que para las cookies
            de análisis y funcionalidad, nos basamos en su consentimiento al continuar con la navegación.</p>

        <h2>4. Cómo Gestionar o Desactivar las Cookies</h2>
        <p>Usted tiene la posibilidad de configurar su navegador para aceptar, bloquear o eliminar las cookies. No obstante, tenga
