            verse limitados.</p>
        <p>Puede modificar la configuración de cookies en su navegador siguiendo estos enlaces:</p>
        <ul>
            <li><strong>Google Chrome:</strong> Configuración > Privacidad y seguridad > Cookies y otros datos de sitios.</li>
            <li><strong>Mozilla Firefox:</strong> Ajustes > Privacidad & Seguridad > Cookies y datos del sitio.</li>
            <li><strong>Microsoft Edge:</strong> Configuración > Cookies y permisos del sitio.</li>
            <li><strong>Safari:</strong> Ajustes > Privacidad > Cookies y datos de sitios web.</li>
        </ul>

